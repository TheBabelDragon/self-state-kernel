#!/usr/bin/env python3
"""Generate crates/self-state-host/src/generated_vectors.rs from vectors/state_vectors.json."""
from __future__ import annotations
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "vectors" / "state_vectors.json"
OUT_PATH = ROOT / "crates" / "self-state-host" / "src" / "generated_vectors.rs"

def rust_value(v):
    if v is None:
        return "JsonValue::Null"
    if isinstance(v, bool):
        return f"JsonValue::Bool({str(v).lower()})"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"JsonValue::I64({v})"
    if isinstance(v, float):
        return f"JsonValue::F64({v})"
    if isinstance(v, dict) and v.get("__special__") == "nan":
        return "JsonValue::SpecialNan"
    if isinstance(v, str):
        return f"JsonValue::String(\"{v}\")"
    raise TypeError(repr(v))

def rust_str(s):
    return json.dumps(s)

def gen_op(op):
    kind = op["op"]
    if kind == "lookup":
        return "Op::Lookup { path: %s, presence: %s }" % (rust_str(op["path"]), rust_str(op["presence"]))
    if kind == "set":
        err = op.get("error")
        err_s = f"Some({rust_str(err)})" if err else "None"
        return "Op::Set { path: %s, value: %s, ok: %s, error: %s }" % (
            rust_str(op["path"]), rust_value(op.get("value")), str(op.get("ok", True)).lower(), err_s)
    if kind == "version":
        return "Op::Version { eq: %d }" % int(op["eq"])
    raise ValueError(kind)

def main():
    doc = json.loads(JSON_PATH.read_text())
    cases = doc["cases"]
    lines = [
        "// @generated by scripts/generate_rust_vectors.py — DO NOT EDIT BY HAND",
        f"// source: vectors/state_vectors.json format={doc.get('format')}",
        "use super::fixture::{Case, JsonValue, Op};",
        "",
        f"pub const FORMAT: &str = {rust_str(doc.get('format', ''))};",
        f"pub const CASE_COUNT: usize = {len(cases)};",
        "",
        "pub static CASES: &[Case] = &[",
    ]
    for case in cases:
        ops = ",\n            ".join(gen_op(op) for op in case["ops"])
        final_paths = case.get("final_paths") or {}
        fp_entries = ",\n            ".join(
            f"({rust_str(k)}, {rust_value(v)})" for k, v in final_paths.items()
        )
        lines.append(
            "    Case {\n"
            f"        name: {rust_str(case['name'])},\n"
            "        ops: &[\n"
            f"            {ops}\n"
            "        ],\n"
            f"        final_version: {int(case.get('final_version', 0))},\n"
            "        final_paths: &[\n"
            f"            {fp_entries}\n"
            "        ],\n"
            "    },"
        )
    lines.append("];")
    lines.append("")
    text = "\n".join(lines) + "\n"
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        if not OUT_PATH.exists() or OUT_PATH.read_text() != text:
            print("generated_vectors.rs is stale; run scripts/generate_rust_vectors.py", file=sys.stderr)
            return 1
        print("generated_vectors.rs up to date")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text)
    print(f"wrote {OUT_PATH} ({len(cases)} cases)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
